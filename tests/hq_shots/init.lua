local function log(s) core.log("action", "[HQ_SHOTS] " .. s) end
core.register_on_joinplayer(function(player)
	if player:get_player_name() ~= "tester" then return end
	core.after(15, function()
		core.set_player_privs("tester", { interact = true, shout = true, server = true, settime = true, weather_manager = true, teleport = true })
		core.after(1, function()
			mcl_gamemode.set_gamemode(player, "survival")
			core.after(1, function()
				core.show_formspec("tester", "", player:get_inventory_formspec())
				core.after(2, function() log("SHOT_READY hq_inv_survival")
				core.after(3, function()
					mcl_gamemode.set_gamemode(player, "creative")
					core.after(1, function()
						local fs = player:get_inventory_formspec()
						log("creative fs len " .. #fs .. " has hq_open " .. tostring(fs:find("hq_open", 1, true)) .. " tail: " .. fs:sub(-260):gsub("\n", " "))
						core.show_formspec("tester", "", fs)
						core.after(2, function() log("SHOT_READY hq_inv_creative")
						core.after(3, function()
							hq.show("tester")
							core.after(2, function() log("SHOT_READY hq_screen")
							core.after(3, function() log("SHOTS_DONE"); core.request_shutdown("done") end) end)
						end) end)
					end)
				end) end)
			end)
		end)
	end)
end)
