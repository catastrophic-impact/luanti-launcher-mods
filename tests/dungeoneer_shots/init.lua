local function log(s) core.log("action", "[DGS] " .. s) end
core.register_on_joinplayer(function(player)
	if player:get_player_name() ~= "tester" then return end
	core.after(16, function()
		core.set_player_privs("tester", { interact = true, shout = true, server = true, fly = true, creative = true })
		dungeoneer.new_run(1, function(run)
			local minp = multiversatile.slot_area("dungeon", run.slot)
			local l = dungeoneer.run_layout(run)
			local function at(r, dx) return vector.new(minp.x + r.cx + (dx or 0), minp.y + r.y0, minp.z + r.cz) end
			-- start room: stand in the west part, look east (+x = yaw -pi/2)
			multiversatile.go(player, at(l.start, -4), { yaw = -math.pi / 2 }, function()
				player:set_look_vertical(0.1)
				log("start room at " .. core.pos_to_string(player:get_pos(), 0) .. " dim=" .. tostring(mcl_worlds.pos_to_dimension(player:get_pos())))
				core.after(8, function() log("SHOT_READY dungeon_start")
					core.after(14, function()
						multiversatile.go(player, at(l.boss, -8), { yaw = -math.pi / 2, remember = false }, function()
							player:set_look_vertical(0.1)
							core.after(8, function() log("SHOT_READY dungeon_boss")
								core.after(14, function() log("SHOTS_DONE"); core.request_shutdown("done") end)
							end)
						end)
					end)
				end)
			end)
		end)
	end)
end)
