local function log(s) core.log("action", "[DGBS] " .. s) end
core.register_on_joinplayer(function(player)
	if player:get_player_name() ~= "tester" then return end
	core.after(16, function()
		core.set_player_privs("tester", { interact = true, shout = true, server = true, fly = true })
		mcl_gamemode.set_gamemode(player, "creative")
		dungeoneer.new_run(1, function(run)
			local minp = multiversatile.slot_area("dungeon", run.slot)
			local L = dungeoneer.run_layout(run)
			multiversatile.go(player, vector.new(minp.x + L.start.cx - 4, minp.y + L.start.y0, minp.z + L.start.cz), { yaw = -math.pi / 2, remember = false }, function()
				player:set_look_vertical(0.1)
				core.after(6, function() log("SHOT_READY nv_off")
					core.after(14, function()
						core.registered_chatcommands.effect.func("tester", "night_vision 1000 1")
						log("meta night_vision=" .. player:get_meta():get_int("night_vision"))
						core.after(8, function() log("SHOT_READY nv_on"); core.after(14, function() log("SHOTS_DONE"); core.request_shutdown("done") end) end)
					end)
				end)
			end)
		end)
	end)
end)
