local function log(s) core.log("action", "[USS_TEST] " .. s) end
core.register_on_joinplayer(function(player)
	if player:get_player_name() ~= "tester" then return end
	core.after(14, function()
		log("prepend has our styles: " .. tostring((player:get_formspec_prepend() or ""):find("style_type[button;", 1, true) ~= nil))
		core.show_formspec("tester", "other:stock", "formspec_version[6]size[8,4.2]label[0.6,0.6;A screen from another mod]button[0.6,1.2;3.2,0.8;a;A stock button]button_exit[4.2,1.2;3.2,0.8;b;Close]field[0.6,2.6;6.8,0.8;f;;some text]")
		core.after(3, function() log("SHOT_READY stock_form") end)
		core.after(6, function()
			core.show_formspec("tester", "", player:get_inventory_formspec())
			core.after(3, function() log("SHOT_READY stock_inventory") end)
		end)
		core.after(13, function()
			core.close_formspec("tester", "")
			core.close_formspec("tester", "other:stock")
			uikit.set(player, "stock", "off")
			log("setting now: " .. uikit.get(player).stock .. " prepend len " .. #(player:get_formspec_prepend() or "") .. " tail=" .. (player:get_formspec_prepend() or ""):sub(-60))
			log("off: prepend has our styles: " .. tostring((player:get_formspec_prepend() or ""):find("style_type[button;", 1, true) ~= nil))
			core.show_formspec("tester", "other:stock", "formspec_version[6]size[8,4.2]label[0.6,0.6;Same screen, option off]button[0.6,1.2;3.2,0.8;a;A stock button]button_exit[4.2,1.2;3.2,0.8;b;Close]field[0.6,2.6;6.8,0.8;f;;some text]")
			core.after(3, function() log("SHOT_READY stock_form_off") end)
			core.after(7, function() log("SHOTS_DONE"); core.request_shutdown("done") end)
		end)
	end)
end)
